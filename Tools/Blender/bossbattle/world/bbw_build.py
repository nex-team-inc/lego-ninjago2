"""Build the Boss Battle world FBXs (gameplay props + arena pieces) - Blender 5.2 headless.

Everything (FBX + manifest + review renders) is regenerated by the venv orchestrator:
    Tools/.venv/bin/python Tools/Blender/bossbattle/world/build_world.py [--only BB_Brick,BB_Rock] [--no-render]

This script alone:
    /Applications/Blender.app/Contents/MacOS/Blender -b --factory-startup --python-exit-code 1 \
        --python Tools/Blender/bossbattle/world/bbw_build.py -- [--only A,B] [--out-dir DIR] [--stats F.json]

Output: <out-dir>/BB_*.fbx (default ninjago-unity/Assets/Models/Ninjago/BossBattle/World). FBX files are rewritten
only when their content changed (bl_common.export_fbx_if_changed through ekit.export_fbx, which also carries the
nested-hierarchy fix). One `WORLD_STATS {json}` line per piece; exit 1 on any contract error:
  * triangle budget per piece;
  * pivot convention ('centre' = bounds centre at the origin, 'bottom' = min y 0 and x/z centred, 'front' = min y 0,
    min z 0 (front face) and x centred, 'top' = max y 0, 'free' = documented per piece);
  * every part non-empty, names unique, rotation/scale baked (parts carry a location only);
  * every UV on a texel centre of the 32x16 palette, in the half (base / emissive) its colour spec asks for.
"""
import json
import math
import os
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bbw_paths as P  # noqa: E402
import bbw_kit as kit  # noqa: E402,F401  (puts ekit / bl_common on sys.path)
import bl_common as bc  # noqa: E402
import bpy  # noqa: E402
import ekit as k  # noqa: E402
import models_bbw_arena as arena  # noqa: E402
import models_bbw_props as props  # noqa: E402

REGISTRY = {**props.REGISTRY, **arena.REGISTRY}
KIND = {**{n: "prop" for n in props.REGISTRY}, **{n: "arena" for n in arena.REGISTRY}}


def check_piece(piece):
    errors = []
    tris = piece.tris()
    if tris > piece.budget:
        errors.append(f"{tris} tris > budget {piece.budget}")
    names = [p.name for p in piece.parts]
    if len(set(names)) != len(names):
        errors.append(f"duplicate part names {names}")
    for p in piece.parts:
        if not p.geo.f:
            errors.append(f"part {p.name} is empty")
        if p.parent and p.parent not in names:
            errors.append(f"part {p.name}: unknown parent {p.parent}")
    lo, hi = piece.bounds(piece.pivot_parts)
    size = hi - lo
    centre = (lo + hi) / 2
    tol = max(0.03, 0.06 * max(size))
    if piece.pivot == "centre":
        if centre.length > tol:
            errors.append(f"pivot 'centre': bounds centre {tuple(round(c, 3) for c in centre)} off by > {tol:.3f}")
    elif piece.pivot == "bottom":
        if abs(lo.y) > 0.005:
            errors.append(f"pivot 'bottom': min y {lo.y:.4f} != 0")
        if abs(centre.x) > tol or abs(centre.z) > tol:
            errors.append(f"pivot 'bottom': x/z centre {centre.x:.3f}, {centre.z:.3f} off by > {tol:.3f}")
    elif piece.pivot == "front":
        if abs(lo.y) > 0.005 or abs(lo.z) > 0.005:
            errors.append(f"pivot 'front': min y {lo.y:.4f} / min z {lo.z:.4f} != 0")
        if abs(centre.x) > tol:
            errors.append(f"pivot 'front': x centre {centre.x:.3f} off by > {tol:.3f}")
    elif piece.pivot == "top":
        if abs(hi.y) > 0.005:
            errors.append(f"pivot 'top': max y {hi.y:.4f} != 0")
    return errors


def check_uvs(obj):
    w, h = bc._PALETTE["size"]
    half = bc._PALETTE["emissiveOffset"]
    me = obj.data
    uvs = me.uv_layers.active.data
    emissive = 0
    for poly in me.polygons:
        cols = set()
        for li in poly.loop_indices:
            u, v = uvs[li].uv
            col, row = u * w - 0.5, (1.0 - v) * h - 0.5
            if abs(col - round(col)) > 1e-3 or abs(row - round(row)) > 1e-3:
                return f"{obj.name}: UV {(u, v)} not at a texel centre", 0
            cols.add((round(col), round(row)))
        if len(cols) != 1:
            return f"{obj.name}: polygon {poly.index} spans {len(cols)} texels", 0
        if next(iter(cols))[0] >= half:
            emissive += 1
    return None, emissive


def bounds_unity(objs):
    pts = []
    for o in objs:
        for v in o.data.vertices:
            b = o.matrix_world @ v.co
            pts.append((-b.x, b.z, -b.y))
    lo = [round(min(p[i] for p in pts), 3) for i in range(3)]
    hi = [round(max(p[i] for p in pts), 3) for i in range(3)]
    return lo, hi


def main():
    def extra(p):
        p.add_argument("--out-dir", default=P.MODELS_OUT)
        p.add_argument("--only", default="")
        p.add_argument("--stats", help="write per-piece stats JSON here")
        p.add_argument("--dry", action="store_true", help="checks only, no FBX export")

    args = bc.parse_args(extra)
    # never fall back to bl_common's Starter/ default palette
    if "Starter" in args.palette_json:
        args.palette_json, args.palette_png = P.PALETTE_JSON, P.PALETTE_PNG
    bc.reset_scene()
    bc.load_palette(args.palette_json)
    mat, *_ = bc.palette_material(args.palette_png, name="M_BB_Palette")
    want = [n for n in args.only.split(",") if n]
    unknown = set(want) - set(REGISTRY)
    if unknown:
        raise SystemExit(f"unknown pieces: {sorted(unknown)}")
    names = want or list(REGISTRY)
    stats, errors = {}, []
    for name in names:
        t = time.time()
        for o in list(bpy.data.objects):
            bpy.data.objects.remove(o, do_unlink=True)
        for me in list(bpy.data.meshes):
            bpy.data.meshes.remove(me)
        piece = REGISTRY[name]()
        if piece.name != name:
            errors.append(f"{name}: builder returned {piece.name}")
        errors += [f"{name}: {e}" for e in check_piece(piece)]
        model = piece.to_model()
        objs = model.build(mat)
        emissive = {}
        for o in objs.values():
            if o.rotation_euler.to_matrix() != o.rotation_euler.to_matrix().Identity(3) or tuple(o.scale) != (1, 1, 1):
                errors.append(f"{name}: part {o.name} carries rotation/scale")
            err, em = check_uvs(o)
            emissive[o.name] = em
            if err:
                errors.append(f"{name}: {err}")
        tris = bc.tri_count(list(objs.values()))
        changed = None
        path = os.path.join(args.out_dir, name + ".fbx")
        if not args.dry:
            os.makedirs(args.out_dir, exist_ok=True)
            _, changed = k.export_fbx(path, list(objs.values()))
        lo, hi = bounds_unity(list(objs.values()))
        st = piece.stats()
        st.update({"kind": KIND[name], "tris_built": tris, "fbx": os.path.relpath(path, P.REPO),
                   "fbx_bytes": os.path.getsize(path) if os.path.exists(path) else 0, "fbx_changed": changed,
                   "built_bounds_min_unity": lo, "built_bounds_max_unity": hi, "emissive_faces_built": emissive,
                   "build_s": round(time.time() - t, 3)})
        for part in st["parts"]:
            o = objs[part["name"]]
            part["local_position_unity"] = [round(-o.location.x, 4), round(o.location.z, 4), round(-o.location.y, 4)]
        stats[name] = st
        print("WORLD_STATS", json.dumps(st))
    if args.stats:
        os.makedirs(os.path.dirname(os.path.abspath(args.stats)), exist_ok=True)
        with open(args.stats, "w") as f:
            json.dump(stats, f, indent=1, sort_keys=True)
    if errors:
        for e in errors:
            print("ERROR", e)
        raise SystemExit(1)


main()
